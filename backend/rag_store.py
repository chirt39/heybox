"""Chroma-backed, Chinese-aware hybrid retrieval for the Nightreign corpus.

Embeddings are generated by the DashScope API so the application server does
not need to load a local PyTorch/SentenceTransformer model.
"""

from __future__ import annotations

import asyncio
import hashlib
import ipaddress
import json
import math
import os
from functools import lru_cache
from pathlib import Path
from urllib.parse import urlsplit

import httpx

from backend.config import positive_int_setting


ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "backend" / "knowledge_base" / "nightreign_knowledge.jsonl"
CHROMA_PATH = Path(os.getenv("CHROMA_PATH", str(ROOT / "local-data" / "chroma")))
ACTIVE_COLLECTION_FILE = CHROMA_PATH / "active_knowledge_collection.json"
COLLECTION_PREFIX = "nightreign_kb_"
GAME_CATEGORIES = ["character", "effect", "enemy", "enemy_scale", "item",
                   "manual_knowledge", "relic", "vessel"]


def validate_api_base_url(value: str, setting_name: str) -> str:
    """Require TLS for credentialed API endpoints, except local development."""
    parsed = None
    try:
        parsed = urlsplit(value)
        hostname = parsed.hostname
        is_loopback = hostname == "localhost"
        if hostname and not is_loopback:
            try:
                is_loopback = ipaddress.ip_address(hostname).is_loopback
            except ValueError:
                pass
    except ValueError:
        hostname = None
        is_loopback = False

    valid = (
        parsed is not None
        and not any(character.isspace() for character in value)
        and hostname is not None
        and parsed.username is None
        and parsed.password is None
        and not parsed.query
        and not parsed.fragment
        and (parsed.scheme == "https" or (parsed.scheme == "http" and is_loopback))
    )
    if not valid:
        raise RuntimeError(
            f"{setting_name} must use HTTPS; HTTP is allowed only for localhost or a loopback IP."
        )
    return value.rstrip("/")


EMBEDDING_API_KEY = os.getenv("DASHSCOPE_API_KEY", "").strip()
EMBEDDING_BASE_URL = validate_api_base_url(
    os.getenv("DASHSCOPE_BASE_URL", "https://dashscope.aliyuncs.com/compatible-mode/v1"),
    "DASHSCOPE_BASE_URL",
)
EMBEDDING_MODEL = os.getenv("DASHSCOPE_EMBEDDING_MODEL", "text-embedding-v4").strip()
EMBEDDING_DIMENSIONS = positive_int_setting("DASHSCOPE_EMBEDDING_DIMENSIONS", 512)
EMBEDDING_CONNECT_TIMEOUT = 10.0
EMBEDDING_READ_TIMEOUT = 45.0
EMBEDDING_WRITE_TIMEOUT = 30.0
EMBEDDING_POOL_TIMEOUT = 10.0
EMBEDDING_OVERALL_TIMEOUT = 60.0


class EmbeddingTimeoutError(TimeoutError):
    """The embedding provider exceeded its request deadline."""


@lru_cache(maxsize=1)
def _chroma():
    import chromadb

    CHROMA_PATH.mkdir(parents=True, exist_ok=True)
    return chromadb.PersistentClient(path=str(CHROMA_PATH))


async def _embed_texts(texts: list[str]) -> list[list[float]]:
    """Generate vectors via DashScope's OpenAI-compatible embeddings endpoint."""
    if not EMBEDDING_API_KEY:
        raise RuntimeError("缺少 DASHSCOPE_API_KEY，无法生成检索向量。")
    if not texts:
        return []

    vectors: list[list[float] | None] = [None] * len(texts)
    timeout = httpx.Timeout(
        connect=EMBEDDING_CONNECT_TIMEOUT,
        read=EMBEDDING_READ_TIMEOUT,
        write=EMBEDDING_WRITE_TIMEOUT,
        pool=EMBEDDING_POOL_TIMEOUT,
    )
    async with httpx.AsyncClient(
        timeout=timeout,
        headers={"Authorization": f"Bearer {EMBEDDING_API_KEY}", "Content-Type": "application/json"},
    ) as client:
        # text-embedding-v4 accepts at most ten texts per synchronous request.
        for offset in range(0, len(texts), 10):
            batch = texts[offset:offset + 10]
            try:
                response = await asyncio.wait_for(
                    client.post(
                        f"{EMBEDDING_BASE_URL}/embeddings",
                        json={"model": EMBEDDING_MODEL, "input": batch,
                              "dimensions": EMBEDDING_DIMENSIONS, "encoding_format": "float"},
                    ),
                    timeout=EMBEDDING_OVERALL_TIMEOUT,
                )
            except (httpx.TimeoutException, asyncio.TimeoutError) as error:
                raise EmbeddingTimeoutError("百炼向量接口请求超时。") from error
            try:
                response.raise_for_status()
            except httpx.HTTPStatusError as error:
                # Include the provider's diagnostic so indexing failures can be
                # corrected without exposing request headers or the API key.
                detail = response.text[:1000].strip()
                raise RuntimeError(
                    f"百炼向量接口请求失败（HTTP {response.status_code}）：{detail or '未返回错误详情'}"
                ) from error
            payload = response.json()
            data = payload.get("data")
            if not isinstance(data, list) or len(data) != len(batch):
                raise RuntimeError("百炼向量接口返回数量与请求文本数量不一致。")
            for row in data:
                index = row.get("index")
                vector = row.get("embedding")
                if not isinstance(index, int) or index < 0 or index >= len(batch) or not isinstance(vector, list):
                    raise RuntimeError("百炼向量接口返回格式无效。")
                vectors[offset + index] = vector

    result = [vector for vector in vectors if vector is not None]
    if len(result) != len(texts) or any(len(vector) != EMBEDDING_DIMENSIONS for vector in result):
        raise RuntimeError("百炼向量维度与配置不一致，请检查模型和向量维数设置。")
    return result


def embed_texts(texts: list[str]) -> list[list[float]]:
    """Run the deadline-bounded async embedding client from synchronous callers."""
    try:
        asyncio.get_running_loop()
    except RuntimeError:
        return asyncio.run(_embed_texts(texts))
    raise RuntimeError("embed_texts must run outside an active event loop.")


def embed_query(text: str) -> list[float]:
    return embed_texts([text])[0]


def corpus_records() -> list[dict]:
    with CORPUS.open(encoding="utf-8") as stream:
        return [json.loads(line) for line in stream if line.strip()]


@lru_cache(maxsize=8)
def _count_source_records(mtime_ns: int, size: int) -> int:
    del mtime_ns, size
    with CORPUS.open(encoding="utf-8") as stream:
        return sum(1 for line in stream if line.strip())


def source_record_count() -> int:
    stat = CORPUS.stat()
    return _count_source_records(stat.st_mtime_ns, stat.st_size)


def _active_collection_name() -> str | None:
    try:
        value = json.loads(ACTIVE_COLLECTION_FILE.read_text(encoding="utf-8"))
        name = value.get("collection")
        return name if isinstance(name, str) and name.startswith(COLLECTION_PREFIX) else None
    except (OSError, ValueError, AttributeError):
        return None


def _get_active_collection():
    name = _active_collection_name()
    if not name:
        return None
    try:
        return _chroma().get_collection(name=name)
    except Exception:
        return None


def _activate_collection(name: str) -> None:
    ACTIVE_COLLECTION_FILE.parent.mkdir(parents=True, exist_ok=True)
    temporary = ACTIVE_COLLECTION_FILE.with_suffix(".tmp")
    temporary.write_text(json.dumps({"collection": name}, ensure_ascii=False), encoding="utf-8")
    temporary.replace(ACTIVE_COLLECTION_FILE)


def status() -> dict:
    collection = _get_active_collection()
    count = int(collection.count()) if collection is not None else 0
    collection_metadata = (collection.metadata or {}) if collection is not None else {}
    model_matches = collection_metadata.get("embedding_model") == EMBEDDING_MODEL
    dimensions_match = collection_metadata.get("embedding_dimensions") == EMBEDDING_DIMENSIONS
    ready = bool(EMBEDDING_API_KEY and collection is not None and count > 0
                 and model_matches and dimensions_match)
    return {
        "status": "ok" if ready else "unavailable",
        "storage": "Chroma",
        "collection": collection.name if collection is not None else None,
        "record_count": count,
        "embedding_model": collection_metadata.get("embedding_model", EMBEDDING_MODEL),
        "embedding_dimensions": EMBEDDING_DIMENSIONS,
    }


def rebuild(batch_size: int = 10) -> dict:
    """Build a versioned collection and switch the active pointer after success."""
    if not EMBEDDING_API_KEY:
        raise RuntimeError("缺少 DASHSCOPE_API_KEY，请先在服务端配置百炼 API Key。")
    records = corpus_records()
    if not records:
        raise ValueError("知识库语料为空，请先运行 python -m backend.index_knowledge。")
    digest = hashlib.sha256(
        CORPUS.read_bytes() + f"{EMBEDDING_MODEL}:{EMBEDDING_DIMENSIONS}".encode()
    ).hexdigest()[:16]
    collection_name = f"{COLLECTION_PREFIX}{digest}"
    db = _chroma()

    if collection_name in db.list_collections():
        collection = db.get_collection(name=collection_name)
        if int(collection.count()) == len(records):
            _activate_collection(collection_name)
            return {"collection": collection_name, "record_count": len(records), "reused": True}
    else:
        collection = db.create_collection(
            name=collection_name,
            metadata={"hnsw:space": "cosine", "embedding_model": EMBEDDING_MODEL,
                      "embedding_dimensions": EMBEDDING_DIMENSIONS},
        )

    # Keep completed batches in the inactive collection if an API request
    # fails. A later rebuild can resume without embedding or billing those
    # already indexed records again.
    chunk_size = min(max(batch_size, 1), 10)
    for offset in range(0, len(records), chunk_size):
        batch = records[offset:offset + chunk_size]
        ids = [str(row["id"]) for row in batch]
        present = set(collection.get(ids=ids, include=[]) .get("ids", []))
        pending = [row for row, row_id in zip(batch, ids) if row_id not in present]
        if not pending:
            continue
        texts = [f"{row['title']}。{row['content']}" for row in pending]
        vectors = embed_texts(texts)
        collection.upsert(
            ids=[str(row["id"]) for row in pending],
            embeddings=vectors,
            documents=[str(row["content"]) for row in pending],
            metadatas=[{
                "category": str(row["category"]), "title": str(row["title"]),
                "source": str(row["source"]),
                "search_text": f"{row['title']} {row['content']} {row.get('keywords', '')}",
            } for row in pending],
        )
    if int(collection.count()) != len(records):
        raise RuntimeError("Chroma 索引数量与源语料不一致。")
    _activate_collection(collection_name)

    return {"collection": collection_name, "record_count": len(records), "reused": False}


@lru_cache(maxsize=1)
def _lexical_index(
    mtime_ns: int, size: int
) -> tuple[list[dict], list[list[str]], dict[str, int], float]:
    del mtime_ns, size
    import jieba

    records = corpus_records()
    documents: list[list[str]] = []
    document_frequency: dict[str, int] = {}
    for row in records:
        text = f"{row.get('title', '')} {row.get('content', '')} {row.get('keywords', '')}"
        tokens = [token.casefold() for token in jieba.cut(text) if token.strip()]
        documents.append(tokens)
        for token in set(tokens):
            document_frequency[token] = document_frequency.get(token, 0) + 1
    average_length = sum(map(len, documents)) / max(1, len(documents))
    idf = [math.log(1 + (len(documents) - frequency + 0.5) / (frequency + 0.5))
           for frequency in document_frequency.values()]
    return records, documents, document_frequency, average_length


def _lexical_search(question: str, selected_categories: list[str], limit: int) -> list[dict]:
    import jieba

    corpus_stat = CORPUS.stat()
    records, documents, document_frequency, average_length = _lexical_index(
        corpus_stat.st_mtime_ns, corpus_stat.st_size
    )
    query_terms = [term.casefold() for term in jieba.cut(question) if term.strip()]
    if not query_terms:
        return []
    allowed = set(selected_categories)
    count = len(documents)
    scores: list[tuple[float, int]] = []
    k1, b = 1.5, 0.75
    for index, (row, tokens) in enumerate(zip(records, documents)):
        if row["category"] not in allowed:
            continue
        frequencies: dict[str, int] = {}
        for token in tokens:
            frequencies[token] = frequencies.get(token, 0) + 1
        length = len(tokens)
        score = 0.0
        for term in query_terms:
            frequency = frequencies.get(term, 0)
            if not frequency:
                continue
            doc_frequency = document_frequency.get(term, 0)
            inverse_frequency = math.log(1 + (count - doc_frequency + 0.5) / (doc_frequency + 0.5))
            score += inverse_frequency * (frequency * (k1 + 1)) / (
                frequency + k1 * (1 - b + b * length / max(1.0, average_length))
            )
        if score > 0:
            scores.append((score, index))
    scores.sort(reverse=True)
    return [{**records[index], "score": score} for score, index in scores[:limit]]


def _dense_search(question: str, selected_categories: list[str], limit: int) -> list[dict]:
    collection = _get_active_collection()
    if collection is None:
        raise RuntimeError("Chroma 知识库尚未建立，请运行 python -m backend.index_knowledge。")
    if not selected_categories or not limit:
        return []
    response = collection.query(
        query_embeddings=[embed_query(question)],
        n_results=min(max(1, limit * 3), int(collection.count())),
        where={"category": {"$in": selected_categories}},
        include=["documents", "metadatas", "distances"],
    )
    ids = response.get("ids", [[]])[0]
    documents = response.get("documents", [[]])[0]
    metadatas = response.get("metadatas", [[]])[0]
    distances = response.get("distances", [[]])[0]
    return [
        {"id": record_id, "content": document, **metadata, "score": 1.0 - float(distance)}
        for record_id, document, metadata, distance in zip(ids, documents, metadatas, distances)
    ][:limit]


def _fuse_rankings(*rankings: list[dict], limit: int) -> list[dict]:
    fused: dict[str, tuple[float, dict]] = {}
    for ranking in rankings:
        for rank, entry in enumerate(ranking, start=1):
            record_id = str(entry["id"])
            score, previous = fused.get(record_id, (0.0, entry))
            fused[record_id] = (score + 1.0 / (60 + rank), previous)
    return [entry for _, entry in sorted(fused.values(), key=lambda item: item[0], reverse=True)[:limit]]


def _retrieve_group(question: str, categories: list[str], limit: int) -> list[dict]:
    if not categories or limit <= 0:
        return []
    dense = _dense_search(question, categories, limit)
    lexical = _lexical_search(question, categories, limit * 3)
    return _fuse_rankings(dense, lexical, limit=limit)


def search(question: str, categories: list[str] | None = None, limit: int = 10) -> list[dict]:
    selected = categories or GAME_CATEGORIES
    manual_categories = ["manual_knowledge"] if "manual_knowledge" in selected else []
    structured_categories = [category for category in selected if category != "manual_knowledge"]
    manual_limit = min(2, max(0, limit - 1)) if manual_categories else 0
    structured = _retrieve_group(question, structured_categories, limit - manual_limit)
    manual = _retrieve_group(question, manual_categories, manual_limit)
    return structured + manual


def chroma_client():
    """Shared persistent Chroma client for retrieval and browser memory."""
    return _chroma()


